from typing import Literal

from pydantic import BaseModel, Field


class ErrorResponse(BaseModel):
    """Describe an HTTP error returned by an API endpoint."""

    detail: str = Field(
        description="Human-readable explanation of why the request failed.",
        examples=["The requested resource was not found"],
    )


class ValidationErrorItem(BaseModel):
    """Describe one request validation failure."""

    loc: list[str | int] = Field(
        description="Location of the invalid value in the request."
    )
    msg: str = Field(description="Human-readable validation message.")
    type: str = Field(description="Machine-readable validation error type.")


class ValidationErrorResponse(BaseModel):
    """Describe FastAPI validation errors and custom filter validation errors."""

    detail: str | list[ValidationErrorItem] = Field(
        description=(
            "Validation message, or the list of field-level validation errors "
            "generated by FastAPI."
        )
    )


class MessageResponse(BaseModel):
    """Describe an endpoint that returns a non-sensitive informational message."""

    message: str = Field(
        description="Informational result of the requested operation.",
        examples=["If an account exists, instructions will be sent"],
    )


class HealthResponse(BaseModel):
    """Describe the application health response."""

    status: Literal["healthy"] = Field(description="Current application status.")
    application: str = Field(description="Configured application name.")
    message: str = Field(description="Human-readable health status message.")


class DatabaseHealthResponse(BaseModel):
    """Describe the database connectivity health response."""

    status: Literal["healthy"] = Field(description="Current database health status.")
    database: Literal["connected"] = Field(
        description="Connectivity state of the configured PostgreSQL database."
    )
    message: str = Field(description="Human-readable database health message.")


class RootResponse(BaseModel):
    """Describe the API welcome response."""

    message: str = Field(description="Welcome message for the API.")
    documentation: str | None = Field(
        description="Documentation path when interactive docs are enabled."
    )


class TokenCheckResponse(BaseModel):
    """Describe the response returned after an access token is verified."""

    authenticated: bool = Field(description="Whether the access token is valid.")
    message: str = Field(description="Human-readable token verification message.")
    subject: str = Field(description="Subject identifier from the verified JWT.")
